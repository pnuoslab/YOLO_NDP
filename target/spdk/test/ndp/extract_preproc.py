#!/usr/bin/env python3
"""
Pull the frame-preprocessing code out of lib/nvmf/ctrlr_bdev.c verbatim, so the
standalone repro harness exercises exactly the code the target runs - not a
hand-copied version that could drift.

Extracts, in order:
  - the four g_sws_* cache globals
  - ndp_resize_darknet_rgb()
  - ndp_frame_to_letterbox_rgb()
and writes them to the output header with a provenance comment.

usage: extract_preproc.py <ctrlr_bdev.c> <out.h> [extra_function ...]
  extra_function: further static functions to copy after the default set,
                  e.g. encode_jpeg_from_rgb.
"""
import re
import sys


def find_function(src, name):
    # A definition: "static <type> *?name(" at line start, then a body.
    m = re.search(r'^static[^\n;]*\b' + re.escape(name) + r'\s*\(', src, re.M)
    if not m:
        sys.exit("extract_preproc: function %s not found" % name)
    start = m.start()
    brace = src.index('{', m.end())
    depth, i = 0, brace
    while i < len(src):
        c = src[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return src[start:i + 1]
        i += 1
    sys.exit("extract_preproc: unbalanced braces in %s" % name)


def main():
    path, out, extra = sys.argv[1], sys.argv[2], sys.argv[3:]
    src = open(path, encoding='utf-8').read()

    g = re.search(r'^static struct SwsContext \*g_sws_ctx[^\n]*\n'
                  r'(?:static [^\n]*g_sws_[^\n]*\n){3}', src, re.M)
    if not g:
        sys.exit("extract_preproc: g_sws_* globals not found")

    parts = [g.group(0),
             find_function(src, 'ndp_resize_darknet_rgb'),
             find_function(src, 'ndp_frame_to_letterbox_rgb')]
    parts += [find_function(src, name) for name in extra]

    with open(out, 'w', encoding='utf-8') as f:
        f.write("/* GENERATED by extract_preproc.py from %s - do not edit. */\n" % path)
        f.write("\n\n".join(parts))
        f.write("\n")


if __name__ == '__main__':
    main()
